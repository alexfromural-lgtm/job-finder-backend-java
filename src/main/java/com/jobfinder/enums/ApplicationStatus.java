package com.jobfinder.enums;

// Defines the statuses a job seeker's application can have
public enum ApplicationStatus {
    // The application has been submitted by the job seeker
    submitted,
    // The recruiter has shortlisted the application
    shortlisted,
    // The recruiter has rejected the application
    rejected,
    // The application is currently under review by the recruiter
    under_review
}
